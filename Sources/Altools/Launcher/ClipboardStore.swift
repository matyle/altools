import AppKit

/// Clipboard history. Polls the pasteboard (macOS has no change notification),
/// keeps text and images, and persists to Application Support.
final class ClipboardStore: ObservableObject {
  static let shared = ClipboardStore()

  struct Item: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image }
    var id = UUID()
    var kind: Kind
    /// The text itself for `.text`; the PNG file name inside the images folder for `.image`.
    var value: String
    var date: Date
    var sourceApp: String?
  }

  @Published private(set) var items: [Item] = []

  private let maxItems = 300
  private var lastChangeCount = NSPasteboard.general.changeCount
  private var ignoredChangeCount: Int?
  private var timer: Timer?
  private var fileURL = AppPaths.support.appendingPathComponent("clipboard.json")
  private let imageDirectory = AppPaths.subdirectory("clipboard-images")

  /// Password managers mark secrets with these types (nspasteboard.org convention).
  private let skippedTypes: Set<NSPasteboard.PasteboardType> = [
    .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
    .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
  ]

  /// In-memory store with fixed items, for rendering previews without real clipboard data.
  init(demoItems: [Item]) {
    items = demoItems
    isDemo = true
  }

  private var isDemo = false

  /// Store persisted to `fileURL` instead of the user's history, for self-tests.
  init(fileURL: URL) {
    self.fileURL = fileURL
  }

  private init() {
    if let data = try? Data(contentsOf: fileURL),
       let saved = try? JSONDecoder().decode([Item].self, from: data) {
      items = saved
    }
  }

  func start() {
    timer?.invalidate()
    timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
  }

  func stop() {
    timer?.invalidate()
    timer = nil
  }

  /// The next pasteboard change is Altools' own (paste-back, restore) and is not recorded.
  func ignoreNextChange() {
    ignoredChangeCount = NSPasteboard.general.changeCount + 1
  }

  func imageURL(for item: Item) -> URL { imageDirectory.appendingPathComponent(item.value) }

  func delete(_ item: Item) {
    items.removeAll { $0.id == item.id }
    if item.kind == .image { try? FileManager.default.removeItem(at: imageURL(for: item)) }
    persist()
  }

  func clear() {
    for item in items where item.kind == .image { try? FileManager.default.removeItem(at: imageURL(for: item)) }
    items = []
    persist()
  }

  /// Puts the item back on the pasteboard and moves it to the top of the history.
  func restoreToPasteboard(_ item: Item) {
    let pb = NSPasteboard.general
    pb.clearContents()
    switch item.kind {
    case .text: pb.setString(item.value, forType: .string)
    case .image:
      if let image = NSImage(contentsOf: imageURL(for: item)) { pb.writeObjects([image]) }
    }
    lastChangeCount = pb.changeCount
    var moved = item
    moved.date = Date()
    items.removeAll { $0.id == item.id }
    items.insert(moved, at: 0)
    persist()
  }

  private func poll() {
    let pb = NSPasteboard.general
    guard pb.changeCount != lastChangeCount else { return }
    lastChangeCount = pb.changeCount
    if let ignored = ignoredChangeCount, pb.changeCount <= ignored {
      if pb.changeCount == ignored { ignoredChangeCount = nil }
      return
    }
    guard AppSettings.shared.clipboardEnabled else { return }
    let types = Set(pb.types ?? [])
    guard types.isDisjoint(with: skippedTypes) else { return }
    let source = NSWorkspace.shared.frontmostApplication?.localizedName

    if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
      insert(Item(kind: .text, value: text, date: Date(), sourceApp: source))
    } else if let image = NSImage(pasteboard: pb), let png = image.pngData() {
      let name = "\(UUID().uuidString).png"
      do {
        try png.write(to: imageDirectory.appendingPathComponent(name))
        insert(Item(kind: .image, value: name, date: Date(), sourceApp: source))
      } catch {
        NSLog("Altools: could not save clipboard image: \(error)")
      }
    }
  }

  private func insert(_ item: Item) {
    if item.kind == .text { items.removeAll { $0.kind == .text && $0.value == item.value } }
    items.insert(item, at: 0)
    while items.count > maxItems {
      let dropped = items.removeLast()
      if dropped.kind == .image { try? FileManager.default.removeItem(at: imageURL(for: dropped)) }
    }
    persist()
  }

  private func persist() {
    guard !isDemo else { return }
    let snapshot = items
    DispatchQueue.global(qos: .utility).async { [fileURL] in
      if let data = try? JSONEncoder().encode(snapshot) { try? data.write(to: fileURL, options: .atomic) }
    }
  }
}

extension NSImage {
  func pngData() -> Data? {
    guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
    return rep.representation(using: .png, properties: [:])
  }
}
